// MAZE — графические ассеты экрана 128×32 (SSD1306, 1 бит).
// Единственный источник для прототипа; в прошивку уйдут они же (экспорт в .h — позже).
// Буквы — шрифт Калейдоскопа (assets/font/kaleidoscope_font.js): цельные ноты —
// Klaatu с точками, диезы — тот же Klaatu без точек.
window.MAZE_ASSETS = (() => {
  const bits = rows => rows.map(r => [...r].map(c => (c === '#' ? 1 : 0)));

  // Геометрия клетки: шаг 8 px, тело тайла 7×7 (столбцы/ряды 0–6),
  // ряд и столбец 7 — зазор, общий с соседями. В зазорах — связки маршрута,
  // уголки указателя.
  const CELL = 8;
  const BODY = 7;

  const NOTE_LETTER = ['C', 'C', 'D', 'D', 'E', 'F', 'F', 'G', 'G', 'A', 'A', 'B'];
  const NOTE_SHARP = [0, 1, 0, 1, 0, 0, 1, 0, 1, 0, 1, 0];
  const NOTE_NAME = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  const OCT_BASE = 5; // C5 = MIDI 72, как в Калейдоскопе (C-1 = 0)
  const OCT_MIN = 2;
  const OCT_MAX = 8;

  // Октава: полоски в одном ряду, их число = отступ от 5-й.
  // Над буквой — выше, под буквой — ниже. Буква сдвигается от полосок на 1 px.
  const STRIPE = {
    1: bits(['#####'])[0],
    2: bits(['##.##'])[0],
    3: bits(['#.#.#'])[0],
  };

  // Неоконченная рамка: уголки по 3 px в зазорах вокруг клетки (x, y от угла тела тайла).
  // Это курсор или указатель — смотря по режиму отметок (в прототипе UI.marks).
  const CORNERS = [
    [-1, -1], [0, -1], [-1, 0],
    [7, -1], [6, -1], [7, 0],
    [-1, 7], [0, 7], [-1, 6],
    [7, 7], [6, 7], [7, 6],
  ];

  // Коды эффектов — одна буква, как столбец эффектов в трекере.
  // [группа, название, полное имя на экране — подсказка в духе LSDj, до 14 знаков]
  const FX = {
    A: ['MIDI', 'арпеджио', 'ARPEGGIO'],
    R: ['MIDI', 'ретчет', 'RETRIGGER'],
    X: ['MIDI', 'акцент', 'ACCENT'],
    P: ['MIDI', 'афтертач (канальный)', 'AFTERTOUCH'],
    I: ['MIDI', 'нота на интервал', 'INTERVAL'],
    L: ['MIDI', 'легато: нота до следующей', 'LEGATO'],
    O: ['тайлы', 'поворот 8 соседей', 'ROTATE AROUND'],
    Z: ['тайлы', 'сдвиг ряда', 'SHIFT ROW'],
    V: ['тайлы', 'сдвиг столбца', 'SHIFT COLUMN'],
    D: ['указатель', 'разворот', 'TURN AROUND'],
    W: ['указатель', 'стоп N шагов, тишина', 'WAIT SILENT'],
    T: ['указатель', 'стоп N шагов, нота тянется', 'WAIT HOLDING'],
    S: ['указатель', 'скорость на ступень', 'SPEED STEP'],
    H: ['указатель', 'прыжок', 'JUMP'],
    K: ['тональность', 'тоника фразы, с такта', 'KEY CHANGE'],
    M: ['тональность', 'сдвиг фразы по ладу', 'MOVE IN SCALE'],
  };
  // Условия проверяются, когда указатель приходит на тайл; соседи — все 8 клеток
  const COND = {
    PASS: 'указатель пришёл на тайл',
    MEET: 'на тайле уже стоит другой указатель',
    NEAR: 'на соседней клетке стоит другой указатель',
    CHNG: 'соседа сдвинул или повернул эффект — тайл взведён до прихода указателя',
  };
  const COND_HELP = { PASS: 'PTR ARRIVES', MEET: 'TWO PTRS HERE', NEAR: 'PTR NEXT DOOR', CHNG: 'NEIGHB MOVED' };

  const SPR = {
    play: bits(['#....', '###..', '#####', '###..', '#....']),
    pause: bits(['##.##', '##.##', '##.##', '##.##', '##.##']),
    // указатель шага в линейном виде
    caret: bits(['..#..', '.###.', '#####']),
  };

  return { CELL, BODY, NOTE_LETTER, NOTE_SHARP, NOTE_NAME, OCT_BASE, OCT_MIN, OCT_MAX, STRIPE, CORNERS, FX, COND, COND_HELP, SPR, bits };
})();
